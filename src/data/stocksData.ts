function generateHistoricalPrices(cmp: number, sma200Val: number, ema50Val: number, volatilityPct: number) {
  const points = 30;
  const history = [];
  const basePrice = cmp * 0.88;
  const dateOffset = new Date();
  dateOffset.setDate(dateOffset.getDate() - 60);

  let current = basePrice;
  for (let i = 0; i < points; i++) {
    const d = new Date(dateOffset);
    d.setDate(d.getDate() + i * 2);

    const progress = i / points;
    const drift = (cmp - basePrice) * progress;
    const randomNoise = (Math.sin(i * 0.7) * 0.03 + (Math.random() - 0.48) * 0.02) * current;
    current = basePrice + drift + randomNoise;

    const ema = ema50Val * (0.94 + progress * 0.06);
    const sma = sma200Val * (0.92 + progress * 0.08);
    const bandWidth = current * (volatilityPct / 100) * 1.8;

    history.push({
      date: d.toLocaleDateString("en-IN", { month: "short", day: "numeric" }),
      price: Math.round(current * 10) / 10,
      ema50: Math.round(ema * 10) / 10,
      sma200: Math.round(sma * 10) / 10,
      upperBand: Math.round((current + bandWidth) * 10) / 10,
      lowerBand: Math.round((current - bandWidth) * 10) / 10,
      volume: Math.round(500000 + Math.random() * 800000),
    });
  }
  history[history.length - 1].price = cmp;
  return history;
}

